  // 闭合折线按弧长均匀重采样成 n 个顶点
  function resample(keys, n) {
    const m = keys.length;
    const seg = [], acc = [0];
    for (let i = 0; i < m; i++) {
      const a = keys[i], b = keys[(i + 1) % m];
      const d = Math.hypot(b[0] - a[0], b[1] - a[1]);
      seg.push({ a, b, d });
      acc.push(acc[i] + d);
    }
    const L = acc[m], out = [];
    for (let i = 0; i < n; i++) {
      const s = L * i / n;
      let k = 0;
      while (k < m - 1 && acc[k + 1] < s) k++;
      const t = seg[k].d ? (s - acc[k]) / seg[k].d : 0;
      out.push([
        seg[k].a[0] + (seg[k].b[0] - seg[k].a[0]) * t,
        seg[k].a[1] + (seg[k].b[1] - seg[k].a[1]) * t
      ]);
    }
    return out;
  }

