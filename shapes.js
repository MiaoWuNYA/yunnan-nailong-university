  // 归一化：整体缩放到最大半径 1，保证各形状尺度一致
  function unit(pts) {
    let m = 0;
    for (const p of pts) m = Math.max(m, Math.hypot(p[0], p[1]));
    if (!m) return pts;
    return pts.map(p => [p[0] / m, p[1] / m]);
  }

  // 整体变形，用来区分四张卡片里本体的姿态
  function deform(pts, sx, sy, tilt) {
    const c = Math.cos(tilt), s = Math.sin(tilt);
    return unit(pts.map(p => {
      const x = p[0] * sx, y = p[1] * sy;
      return [x * c - y * s, x * s + y * c];
    }));
  }

